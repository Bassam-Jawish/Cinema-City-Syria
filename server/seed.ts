/**
 * Demo data: the rolling schedule window and the seeded bookings that make the halls look lived-in.
 *
 * Seeding is deterministic per showtime (a PRNG keyed by the showtime id) given the same clock, so
 * two resets at the same moment produce identical data. All writes happen in one transaction with
 * prepared statements.
 */
import type { DatabaseSync } from 'node:sqlite';
import { SCHEDULE_DAYS } from '../shared/constants';
import type { SeatInfo } from '../shared/hall';
import { addDays, cinemaDate, cinemaDateTimeToUtc, daysBetween, isWeekend } from '../shared/time';
import type { BookingStatus, Movie, PaymentMethod, PaymentStatus } from '../shared/types';
import { loadCatalog, syncCatalog, type CatalogRuntime, type HallRuntime } from './catalog-store';
import { makeBookingCode } from './codes';
import { CATALOG } from './data/catalog';
import { FAMILY_NAMES, FIRST_NAMES } from './data/names';
import { PROGRAMMES, planDay, type PlannedShowtime, type Programmes } from './data/schedule';
import { transaction } from './db';
import { pick, pickWeighted, randomIndex, seededRandom, type Random } from './random';

const MINUTE = 60_000;
const DAY = 24 * 60 * MINUTE;

/** How full seeded showtimes are. Target = base by days ahead × modifiers ± noise, clamped. */
export const SEED_OCCUPANCY = {
  /** Index = days from today (cinema date). */
  byDaysAhead: [0.55, 0.42, 0.33, 0.26, 0.2, 0.15, 0.12],
  evening: { from: 18 * 60, factor: 1.35 },
  matinee: { before: 15 * 60, factor: 0.6 },
  weekend: 1.25,
  featured: 1.15,
  noise: 0.1,
  min: 0.04,
  max: 0.92,
  /** Today's 20:15 show in Hall 1 is kept nearly full so "filling fast" is visible in the demo. */
  showcase: { hallId: 'hall-1', time: '20:15', occupancy: 0.88 },
} as const;

/** Party sizes with their weights (percent). */
const PARTY_SIZES: ReadonlyArray<readonly [number, number]> = [
  [1, 12],
  [2, 42],
  [3, 18],
  [4, 18],
  [5, 7],
  [6, 3],
];
const ARABIC_SCRIPT_SHARE = 0.75;
const BOX_OFFICE_SHARE = 0.7;
const CHECKED_IN_SHARE = 0.85;
/** Second digit of Syrian mobile numbers after +963 9. */
const MOBILE_PREFIXES = ['3', '4', '5', '6', '8', '9'];
/** View-score points of randomness when choosing where a party sits, and the penalty for leaving a lone seat. */
const PLACEMENT_NOISE = 30;
const LONE_SEAT_PENALTY = 12;

export interface SeedOptions {
  /** Generate demo bookings for newly created showtimes. */
  seedBookings: boolean;
  /** Which films each hall rotates through (default: server/data/schedule.ts). */
  programmes?: Programmes;
}

export interface ResetOptions extends SeedOptions {
  /** The film catalogue to re-read (default: server/data/catalog.ts). */
  movies?: readonly Movie[];
}

export interface ScheduleSummary {
  /** Calendar days generated by this call. */
  dates: string[];
  showtimes: number;
  bookings: number;
  seats: number;
}

/** Contiguous seats of one row within one block, left to right. */
type Segment = readonly SeatInfo[];

function segmentsOf(hall: HallRuntime): Segment[] {
  const segments: Segment[] = [];
  for (const row of hall.geometry.rows) {
    let current: SeatInfo[] = [];
    for (const seat of row.seats) {
      if (current.length > 0 && current[current.length - 1].block !== seat.block) {
        segments.push(current);
        current = [];
      }
      current.push(seat);
    }
    if (current.length > 0) segments.push(current);
  }
  return segments;
}

const clamp = (value: number, min: number, max: number): number => Math.min(max, Math.max(min, value));

export function targetOccupancy(show: PlannedShowtime, movie: Movie, today: string, rand: Random): number {
  const o = SEED_OCCUPANCY;
  const daysAhead = clamp(daysBetween(today, show.date), 0, o.byDaysAhead.length - 1);
  let target: number = o.byDaysAhead[daysAhead];
  if (show.startMinutes >= o.evening.from) target *= o.evening.factor;
  if (show.startMinutes < o.matinee.before) target *= o.matinee.factor;
  if (isWeekend(show.date)) target *= o.weekend;
  if (movie.featured) target *= o.featured;
  target = clamp(target + (rand() * 2 - 1) * o.noise, o.min, o.max);
  if (show.date === today && show.hallId === o.showcase.hallId && show.time === o.showcase.time) target = o.showcase.occupancy;
  return target;
}

/**
 * The best free window of `size` seats, scored by average view (with noise, so the centre fills
 * first but not like clockwork) and penalised for stranding a single empty seat beside it.
 */
function bestWindow(segments: readonly Segment[], taken: ReadonlySet<string>, size: number, rand: Random): SeatInfo[] | null {
  let best: { segment: Segment; start: number } | null = null;
  let bestScore = -Infinity;
  for (const segment of segments) {
    if (segment.length < size) continue;
    let run = 0;
    for (let i = 0; i < segment.length; i++) {
      if (taken.has(segment[i].id)) {
        run = 0;
        continue;
      }
      run++;
      if (run < size) continue;
      const start = i - size + 1;
      let sum = 0;
      for (let k = start; k <= i; k++) sum += segment[k].viewScore;
      let score = sum / size + rand() * PLACEMENT_NOISE;
      if (run - size === 1) score -= LONE_SEAT_PENALTY;
      const loneOnRight = i + 1 < segment.length && !taken.has(segment[i + 1].id) && (i + 2 >= segment.length || taken.has(segment[i + 2].id));
      if (loneOnRight) score -= LONE_SEAT_PENALTY;
      if (score > bestScore) {
        bestScore = score;
        best = { segment, start };
      }
    }
  }
  return best ? best.segment.slice(best.start, best.start + size) : null;
}

/** Seats parties of 1–6 in contiguous seats of one row and block until `target` seats are taken. */
export function placeParties(segments: readonly Segment[], target: number, rand: Random): SeatInfo[][] {
  const taken = new Set<string>();
  const parties: SeatInfo[][] = [];
  let remaining = target;
  while (remaining > 0) {
    let size = Math.min(pickWeighted(rand, PARTY_SIZES), remaining);
    let party: SeatInfo[] | null = null;
    // A party that fits nowhere (a nearly full hall, or seats in pairs) books fewer seats.
    while (size > 0 && !(party = bestWindow(segments, taken, size, rand))) size--;
    if (!party) break;
    for (const seat of party) taken.add(seat.id);
    parties.push(party);
    remaining -= party.length;
  }
  return parties;
}

function customerName(rand: Random): string {
  const first = pick(rand, FIRST_NAMES);
  const family = pick(rand, FAMILY_NAMES);
  return rand() < ARABIC_SCRIPT_SHARE ? `${first.ar} ${family.ar}` : `${first.en} ${family.en}`;
}

function mobileNumber(rand: Random): string {
  let digits = pick(rand, MOBILE_PREFIXES);
  for (let i = 0; i < 7; i++) digits += String(randomIndex(rand, 10));
  return `+9639${digits}`;
}

type Seeder = (show: PlannedShowtime) => { bookings: number; seats: number };

function createSeeder(db: DatabaseSync, catalog: CatalogRuntime, now: number): Seeder {
  const today = cinemaDate(now);
  const insertBooking = db.prepare(
    `INSERT INTO bookings (code, showtime_id, session_id, status, customer_name, customer_phone, payment_method,
       payment_status, total, currency, seeded, created_at, cancelled_at, checked_in_at)
     VALUES (?, ?, NULL, ?, ?, ?, ?, ?, ?, 'SYP', 1, ?, NULL, ?)`,
  );
  const insertSeat = db.prepare(
    `INSERT INTO booking_seats (booking_code, showtime_id, seat_id, row_label, seat_number, seat_type, price, active)
     VALUES (?, ?, ?, ?, ?, ?, ?, 1)`,
  );
  const codes = new Set(
    (db.prepare('SELECT code FROM bookings').all() as unknown as Array<{ code: string }>).map((row) => row.code),
  );
  const segmentsByHall = new Map<string, Segment[]>();

  return (show) => {
    const hall = catalog.halls.get(show.hallId);
    const movie = catalog.movies.get(show.movieId);
    if (!hall || !movie) return { bookings: 0, seats: 0 };
    let segments = segmentsByHall.get(hall.definition.id);
    if (!segments) {
      segments = segmentsOf(hall);
      segmentsByHall.set(hall.definition.id, segments);
    }

    const rand = seededRandom(`seed:${show.id}`);
    const target = Math.round(targetOccupancy(show, movie, today, rand) * hall.geometry.seatCount);
    const parties = placeParties(segments, target, rand);
    const started = now >= show.startsAt;
    const reference = Math.min(show.startsAt, now);
    // Booked between 6 days and 10 minutes before the show (or before now, for shows that have
    // started) — and, for a film on advance sale, not before the sale opened.
    const latest = reference - 10 * MINUTE;
    const saleOpened = movie.advanceBookingFrom ? cinemaDateTimeToUtc(movie.advanceBookingFrom, '00:00').getTime() : Number.NEGATIVE_INFINITY;
    const earliest = Math.max(reference - 6 * DAY, Math.min(saleOpened, latest));
    let seats = 0;

    for (const party of parties) {
      let code = makeBookingCode((n) => randomIndex(rand, n));
      while (codes.has(code)) code = makeBookingCode((n) => randomIndex(rand, n));
      codes.add(code);

      const name = customerName(rand);
      const phone = mobileNumber(rand);
      const method: PaymentMethod = rand() < BOX_OFFICE_SHARE ? 'box_office' : 'online_demo';
      const createdAt = Math.floor((latest - rand() * (latest - earliest)) / 1000) * 1000;
      let status: BookingStatus = 'confirmed';
      let payment: PaymentStatus = method === 'online_demo' ? 'paid' : 'due';
      let checkedInAt: number | null = null;
      if (started && rand() < CHECKED_IN_SHARE) {
        status = 'checked_in';
        payment = 'paid';
        checkedInAt = clamp(Math.floor(show.startsAt - rand() * 30 * MINUTE), createdAt + MINUTE, now);
      }

      const priced = party.map((seat) => ({ seat, price: show.prices[seat.type] ?? 0 }));
      const total = priced.reduce((sum, { price }) => sum + price, 0);
      insertBooking.run(code, show.id, status, name, phone, method, payment, total, createdAt, checkedInAt);
      for (const { seat, price } of priced) {
        insertSeat.run(code, show.id, seat.id, seat.row, seat.number, seat.type, price);
      }
      seats += party.length;
    }
    return { bookings: parties.length, seats };
  };
}

/** The calendar days of the window that starts today (cinema time). */
export function scheduleWindow(now: number): string[] {
  const today = cinemaDate(now);
  return Array.from({ length: SCHEDULE_DAYS }, (_, i) => addDays(today, i));
}

/** A film's first week in the cinema: its release date and the six days after. */
export function openingWeek(movie: Pick<Movie, 'releaseDate'>): string[] {
  return Array.from({ length: SCHEDULE_DAYS }, (_, i) => addDays(movie.releaseDate, i));
}

/** Whether the film has not opened yet but its opening week is already on sale. */
export function inAdvanceBooking(movie: Pick<Movie, 'releaseDate' | 'advanceBookingFrom'>, today: string): boolean {
  return movie.advanceBookingFrom !== null && movie.advanceBookingFrom <= today && today < movie.releaseDate;
}

/**
 * The days a film's page offers: the regular window, or — for a film in advance booking that
 * opens after the window — its opening week.
 */
export function bookingDays(movie: Pick<Movie, 'releaseDate' | 'advanceBookingFrom'>, now: number): string[] {
  const window = scheduleWindow(now);
  return inAdvanceBooking(movie, cinemaDate(now)) && movie.releaseDate > window[window.length - 1] ? openingWeek(movie) : window;
}

/** Every day that must have showtimes: today … today + 6, plus the opening weeks on advance sale. */
export function scheduleDates(movies: readonly Movie[], now: number): string[] {
  const today = cinemaDate(now);
  const dates = new Set(scheduleWindow(now));
  for (const movie of movies) if (inAdvanceBooking(movie, today)) for (const date of openingWeek(movie)) dates.add(date);
  return [...dates].sort();
}

/**
 * Makes sure showtimes exist for today … today + 6 and for the opening week of every film on
 * advance sale. Days generated before are left alone (and old showtimes are kept); each new day
 * gets its showtimes and, if enabled, its demo bookings.
 */
export function ensureScheduleWindow(db: DatabaseSync, catalog: CatalogRuntime, now: number, options: SeedOptions): ScheduleSummary {
  const dates = scheduleDates(catalog.activeMovies, now);
  const summary: ScheduleSummary = { dates: [], showtimes: 0, bookings: 0, seats: 0 };
  const knownDays = db.prepare('SELECT date FROM schedule_days WHERE date >= ? AND date <= ?');
  const missingDays = (): string[] => {
    const known = new Set((knownDays.all(dates[0], dates[dates.length - 1]) as unknown as Array<{ date: string }>).map((r) => r.date));
    return dates.filter((date) => !known.has(date));
  };
  // Cheap read first: most calls find nothing to do and should not take the write lock.
  if (missingDays().length === 0) return summary;

  return transaction(db, () => {
    const missing = missingDays();
    if (missing.length === 0) return summary;
    const insertShowtime = db.prepare(
      `INSERT OR IGNORE INTO showtimes (id, movie_id, hall_id, date, starts_at, ends_at, format, prices)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
    );
    const markDay = db.prepare('INSERT OR REPLACE INTO schedule_days (date, generated_at) VALUES (?, ?)');
    const seed = options.seedBookings ? createSeeder(db, catalog, now) : null;
    const programme = new Map(catalog.activeMovies.map((movie) => [movie.id, movie]));
    const halls = catalog.activeHalls.map((hall) => ({ id: hall.definition.id, seatTypes: hall.seatTypes }));

    for (const date of missing) {
      for (const show of planDay(date, programme, halls, options.programmes ?? PROGRAMMES)) {
        const { changes } = insertShowtime.run(
          show.id,
          show.movieId,
          show.hallId,
          show.date,
          show.startsAt,
          show.endsAt,
          show.format,
          JSON.stringify(show.prices),
        );
        if (!changes) continue;
        summary.showtimes++;
        if (seed) {
          const seeded = seed(show);
          summary.bookings += seeded.bookings;
          summary.seats += seeded.seats;
        }
      }
      markDay.run(date, now);
      summary.dates.push(date);
    }
    return summary;
  });
}

/**
 * Full demo reset: deletes every hold, booking and showtime, re-reads films and halls from code,
 * and regenerates the schedule window (with demo bookings if enabled). Returns the fresh catalogue.
 */
export function resetDemoData(
  db: DatabaseSync,
  now: number,
  options: ResetOptions,
): { catalog: CatalogRuntime; summary: ScheduleSummary } {
  return transaction(db, () => {
    db.exec(
      'DELETE FROM holds; DELETE FROM booking_seats; DELETE FROM bookings; DELETE FROM showtimes; DELETE FROM schedule_days;',
    );
    syncCatalog(db, options.movies ?? CATALOG);
    // Nothing references retired films or halls any more.
    db.exec('DELETE FROM movies WHERE active = 0; DELETE FROM halls WHERE active = 0;');
    const catalog = loadCatalog(db);
    const summary = ensureScheduleWindow(db, catalog, now, options);
    return { catalog, summary };
  });
}
